function inferKibbleSizeSuitability(food: FoodItem): BreedSize[] {
  if (food.kibbleSizeSuitability && food.kibbleSizeSuitability.length > 0) {
    return food.kibbleSizeSuitability;
  }
  const n = `${food.brand} ${food.name}`.toLowerCase();
  if (food.type === 'wet') return ['toy', 'small', 'medium', 'large', 'giant'];
  if (n.includes('mini') || n.includes('pequeñ') || n.includes('small') || n.includes('toy')) {
    return ['toy', 'small'];
  }
  if (n.includes('maxi') || n.includes('grandes') || n.includes('large')) {
    return ['large', 'giant'];
  }
  if (n.includes('medium') || n.includes('mediano')) {
    return ['medium'];
  }
  return ['toy', 'small', 'medium', 'large'];
}

